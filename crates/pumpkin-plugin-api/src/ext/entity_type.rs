impl EntityType {
    /// Returns the bare resource name (e.g. `"zombie"`).
    #[must_use]
    pub fn as_str(self) -> &'static str {
        RESOURCE_NAMES[self as usize]
    }

    /// Returns the namespaced resource location (e.g. `"minecraft:zombie"`).
    #[must_use]
    pub fn resource_location(self) -> &'static str {
        RESOURCE_LOCATIONS[self as usize]
    }

    /// Resolves an entity type from a registry key such as `"minecraft:zombie"`,
    /// `"zombie"` or `"zombie_horse"`. Returns `None` for unknown or modded types.
    #[must_use]
    pub fn from_registry_key(key: &str) -> Option<Self> {
        let name = key.strip_prefix("minecraft:").unwrap_or(key);
        RESOURCE_NAMES
            .iter()
            .position(|candidate| *candidate == name)
            .and_then(|index| u8::try_from(index).ok())
            .map(|index| {
                // SAFETY: `index` comes from a position in `RESOURCE_NAMES`, which has one
                // entry per WIT enum variant, so it is a valid discriminant.
                unsafe { std::mem::transmute::<u8, Self>(index) }
            })
    }
}

impl std::fmt::Display for EntityType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.resource_location())
    }
}

impl AsRef<str> for EntityType {
    fn as_ref(&self) -> &str {
        self.resource_location()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_key_round_trip() {
        let zombie = EntityType::from_registry_key("minecraft:zombie");
        assert_eq!(zombie.map(EntityType::resource_location), Some("minecraft:zombie"));
        assert_eq!(zombie.map(EntityType::as_str), Some("zombie"));
        assert_eq!(EntityType::from_registry_key("zombie_horse"), Some(EntityType::ZombieHorse));
        assert_eq!(EntityType::from_registry_key("minecraft:not_a_mob"), None);
    }
}
