#!/usr/bin/env bash
# gen-todo.sh  -- rebuild docs/TODO.md from docs/queue-*.tsv minus numbers listed in docs/DONE.md.
source "$(dirname "$0")/lib.sh"; cd "$KAB_ROOT"
python3 - <<'PY'
import re
done=set(re.findall(r'#(\d+)',open('docs/DONE.md').read())) if __import__('os').path.exists('docs/DONE.md') else set()
out=["# TODO (pending upstream items)\nGenerated by scripts/gen-todo.sh. Mark done by listing `#N` in docs/DONE.md.\n","## Pull requests (smallest first)\n| # | lines | files | merge | title |\n|---|---|---|---|---|"]
rows=[l.rstrip('\n').split('\t') for l in open('docs/queue-prs.tsv')]
rows=[r for r in rows if r[0] not in done]; rows.sort(key=lambda r:int(r[1]))
for r in rows: out.append(f"| #{r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[5][:90].replace('|','/')} |")
out+=["","## Issues\n| # | title | labels |\n|---|---|---|"]
rows=[l.rstrip('\n').split('\t') for l in open('docs/queue-issues.tsv')]
for r in rows:
    if r[0] not in done: out.append(f"| #{r[0]} | {r[1][:100].replace('|','/')} | {r[2] if len(r)>2 else ''} |")
open('docs/TODO.md','w').write("\n".join(out)+"\n")
PY
echo "TODO regenerated"
