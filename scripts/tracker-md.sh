#!/usr/bin/env bash
# tracker-md.sh [--commit] -- regenerate TRACKER.md from docs/PARITY.tsv, our commits (upstream/master..master) and live workers.
# State per gap row: LANDED (a commit on master names it), IN-FLIGHT (running audit worker or unlanded kab/t* branch), OPEN.
# --commit also commits and pushes TRACKER.md when it changed (at most what the caller's cadence allows).
source "$(dirname "$0")/lib.sh"; set +e; cd "$KAB_ROOT"
python3 - <<'PY'
import csv, collections, hashlib, re, subprocess, time

def sh(*a):
    return subprocess.run(a, capture_output=True, text=True).stdout

def slug_of(cat, name):  # same slug as tracker-refill.sh so worker names map back to rows
    full = cat + '-' + name
    return 't' + re.sub(r'[^a-z0-9]+', '-', full.lower()).strip('-')[:32] + '-' + hashlib.md5(full.encode()).hexdigest()[:6]

rows = list(csv.DictReader(open('docs/PARITY.tsv'), delimiter='\t'))
commits = [l.split('\t', 1) for l in sh('git', 'log', '--format=%h\t%s', 'upstream/master..master').splitlines() if '\t' in l]
norm = lambda s: re.sub(r'[^a-z0-9]+', '_', s.lower()).strip('_')
subj = [(h, s, '_' + norm(s) + '_') for h, s in commits if not re.match(r'^(docs|chore|perf)\((scripts|queue|sync|tracker|worker|orchestration)', s)]

running = {l.split()[0] for l in sh('scripts/oc-status.sh').splitlines() if l.endswith(' running')}
unlanded = set()
for b in sh('git', 'for-each-ref', '--format=%(refname:short)', 'refs/heads/kab/t*').split():
    if '+' in [l[:1] for l in sh('git', 'cherry', 'master', b).splitlines()]:
        unlanded.add(b[4:])

DONE_COVER = {'COVERED-DONE', 'FIXED-ON-MASTER', 'COVERED-SKIPPED', 'DESIGN'}
out = collections.OrderedDict()
detail = []
for r in rows:
    cat, name, cov = r['category'], r['name'], r['covered']
    if cov == 'n/a':
        out.setdefault(cat, collections.Counter())['no gap'] += 1; continue
    n = norm(name)
    hits = [h for h, s, ns in subj if len(n) >= 4 and '_' + n + '_' in ns][:4]
    slug = slug_of(cat, name)
    if hits or cov in DONE_COVER: state = 'LANDED' if hits else 'DONE'
    elif slug in running or slug in unlanded: state = 'IN-FLIGHT'
    else: state = 'OPEN'
    out.setdefault(cat, collections.Counter())[state] += 1
    detail.append((cat, name, r['status'], cov, state, r['issues'], hits, r['note'], slug in running))

lines = ['# Parity tracker', '',
         'Generated by `scripts/tracker-md.sh` from `docs/PARITY.tsv`, our commits on top of upstream (`upstream/master..master`) and live workers. '
         'Do not edit by hand: `scripts/tracker-watch.sh` rebuilds it whenever master or a worker changes.', '',
         '- Master: `%s` (%d commits ahead of upstream)' % (sh('git', 'rev-parse', '--short', 'master').strip(), len(commits)),
         '- Updated: %s' % time.strftime('%Y-%m-%d %H:%M'),
         '- Matching is by name in commit subjects on master, so LANDED means "a fix naming it landed", not that the vanilla audit is complete.',
         '- States: **LANDED** a commit on master names it, **DONE** tracker marks it covered, **IN-FLIGHT** audit worker running or branch awaiting integration, **OPEN** nothing yet', '',
         '## Progress by category', '', '| Category | Rows | No gap | LANDED/DONE | IN-FLIGHT | OPEN | Gaps closed |', '|---|---|---|---|---|---|---|']
tot = collections.Counter()
for cat, c in out.items():
    gaps = c['LANDED'] + c['DONE'] + c['IN-FLIGHT'] + c['OPEN']
    closed = c['LANDED'] + c['DONE']
    pct = ('%d%%' % round(100 * closed / gaps)) if gaps else '-'
    lines.append('| %s | %d | %d | %d | %d | %d | %s |' % (cat, sum(c.values()), c['no gap'], closed, c['IN-FLIGHT'], c['OPEN'], pct))
    tot.update(c)
gaps = tot['LANDED'] + tot['DONE'] + tot['IN-FLIGHT'] + tot['OPEN']; closed = tot['LANDED'] + tot['DONE']
lines.append('| **all** | %d | %d | %d | %d | %d | **%s** |' % (sum(tot.values()), tot['no gap'], closed, tot['IN-FLIGHT'], tot['OPEN'], ('%d%%' % round(100 * closed / gaps)) if gaps else '-'))
lines += ['', '## Gap rows', '', '| State | Category | Name | Tracker | Issues | Commits | Note |', '|---|---|---|---|---|---|---|']
order = {'IN-FLIGHT': 0, 'OPEN': 1, 'LANDED': 2, 'DONE': 3}
for cat, name, status, cov, state, issues, hits, note, live in sorted(detail, key=lambda d: (order[d[4]], d[0], d[1])):
    lines.append('| %s%s | %s | %s | %s/%s | %s | %s | %s |' % (state, ' (running)' if live else '', cat, name, status, cov, issues, ' '.join('`%s`' % h for h in hits) or '-', note.replace('|', '/')[:140]))
open('TRACKER.md', 'w').write('\n'.join(lines) + '\n')
PY
if [ "${1:-}" = "--commit" ]; then
  if [ -z "$(git ls-files TRACKER.md)" ] || ! git diff --quiet -- TRACKER.md; then
    git add TRACKER.md && git commit -q --only TRACKER.md -m "docs(tracker): refresh parity progress" && git push -q origin master 2>&1 | tail -n 1
  fi
fi
