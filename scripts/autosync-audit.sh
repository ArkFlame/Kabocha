#!/usr/bin/env bash
# Two-hour automatic audit of upstream Pumpkin: new commits plus open issues/PRs
# not yet recorded in docs/LEDGER.tsv. Writes docs/AUTO_AUDIT.md and commits it
# only when the content actually changes. Never edits source or runs builds.
set -uo pipefail
export PATH="/home/linsaftw/.cargo/bin:/usr/local/bin:/usr/bin:/bin"
KAB=/run/media/linsaftw/SDD/GitHub/ArkFlame/Kabocha
LOG=/tmp/kab-autosync.log
exec 9>/tmp/kab-autosync.lock
flock -n 9 || { printf '%s already running\n' "$(date -u +%FT%TZ)" >> "$LOG"; exit 0; }
cd "$KAB" || exit 1
mkdir -p .git/kab-autosync
git fetch -q upstream || { printf 'fetch failed\n' >> "$LOG"; exit 1; }
head_up=$(git rev-parse upstream/master)
ahead=$(git rev-list --count upstream/master..master)
behind=$(git rev-list --count master..upstream/master)
last=$(cat .git/kab-autosync/last-upstream 2>/dev/null || true)
new_commits=''
if [ -n "$last" ] && [ "$last" != "$head_up" ]; then
  new_commits=$(git log --oneline "$last..$head_up" | head -40)
fi
printf '%s\n' "$head_up" > .git/kab-autosync/last-upstream
report=docs/AUTO_AUDIT.md
{
  echo '# Automatic upstream audit'
  echo
  echo 'Generated by scripts/autosync-audit.sh (cron, every 2 hours). Do not edit by hand.'
  echo 'Act on anything under NEEDS ACTION in the next orchestration pass.'
  echo
  echo "Upstream: $head_up | ahead $ahead, behind $behind"
  echo
  echo '## New upstream commits since last audit'
  echo
  if [ -n "$new_commits" ]; then printf '%s\n' "$new_commits"; else echo '(none)'; fi
  echo
  echo '## NEEDS ACTION: open upstream items not in docs/LEDGER.tsv'
  echo
  python3 - <<'PY'
import csv, json, subprocess
known = set()
with open('docs/LEDGER.tsv', newline='') as f:
    for row in csv.DictReader(f, delimiter='\t'):
        known.add((row['kind'], row['number']))
for kind, args in (
    ('pr', ['pr', 'list', '-R', 'Pumpkin-MC/Pumpkin', '--state', 'open', '--limit', '1000',
            '--json', 'number,title,updatedAt']),
    ('issue', ['issue', 'list', '-R', 'Pumpkin-MC/Pumpkin', '--state', 'open', '--limit', '1000',
               '--json', 'number,title,updatedAt']),
):
    try:
        items = json.loads(subprocess.check_output(['gh'] + args, text=True))
    except Exception as exc:
        print(f'- ERROR listing {kind}s: {exc}')
        continue
    pending = [i for i in items if (kind, str(i['number'])) not in known]
    label = {'pr': 'PRs', 'issue': 'ISSUES'}[kind]
    print(f'### {label}: {len(pending)} untracked of {len(items)} open')
    for i in sorted(pending, key=lambda x: -x['number']):
        print(f"- #{i['number']} {i['title']} (updated {i['updatedAt'][:10]})")
    print()
PY
} > "$report"
if ! git diff --quiet -- "$report"; then
  git add -- "$report"
  git commit -q -m "chore(audit): refresh automatic upstream audit [skip ci]" -- "$report" || echo 'commit failed' >> "$LOG"
  git push -q origin master || echo 'push failed (will retry next run)' >> "$LOG"
fi
printf '%s audit done: ahead=%s behind=%s\n' "$(date -u +%FT%TZ)" "$ahead" "$behind" >> "$LOG"
